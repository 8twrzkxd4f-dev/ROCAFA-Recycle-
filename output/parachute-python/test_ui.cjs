const { chromium }=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1100,height:900}});const errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 await page.goto('http://127.0.0.1:8765/');
 await page.waitForFunction(()=>document.getElementById('ph-vt').textContent.includes('m/s'));
 await page.locator('#pw-d').fill('3');
 await page.waitForFunction(()=>window.parachuteGeometry.main.d===3);
 await page.locator('#vv-sync').click();
 assert(Math.abs(Number(await page.locator('#vv-main_area').inputValue())-Math.PI*2.25)<.001);
 await page.locator('#vv-main_area').fill('6.05');
 await page.locator('#vv-run').click();
 await page.waitForFunction(()=>document.getElementById('vv-status').textContent.includes('模擬到達地面'));
 assert.equal(await page.locator('#vv-force svg').count(),1);
 await page.locator('#vv-focus').selectOption('main');
 await page.locator('#vv-dynamic').screenshot({path:'vv-desktop.png'});
 await page.locator('#vv-converge').click();
 await page.waitForFunction(()=>document.getElementById('vv-status').textContent.includes('敏感度檢查完成'));
 assert.equal(await page.locator('#vv-conv tbody tr').count(),3);
 await page.locator('#vv-mode').selectOption('6dof');
 assert((await page.locator('#vv-status').textContent()).includes('參數已更改'));
 await page.locator('#vv-advanced').evaluate(e=>e.parentElement.open=true);
 await page.locator('#vv-wind_x').fill('5');
 await page.locator('#vv-run').click();
 await page.waitForFunction(()=>document.getElementById('vv-status').textContent.includes('模擬到達地面'));
 const res=await page.request.post('http://127.0.0.1:8765/api/simulate',{data:{mode:'6dof',wind_x:5}});
 const simulation=await res.json();
 assert(simulation.summary.drift_m>0);
 const rows=simulation.rows.slice(2,10);
 await page.locator('#vv-observations').fill('time_s,force_n\n'+rows.map(r=>r.time_s+','+r.force_n).join('\n'));
 await page.locator('#vv-validate').click();
 await page.waitForFunction(()=>document.getElementById('vv-validation-result').textContent.includes('RMSE'));
 assert.equal(await page.locator('#vv-overlay svg').count(),1);
 await page.locator('#vv-mesh').evaluate(e=>e.closest('details').open=true);
 await page.locator('#vv-mesh').fill('h_m,cd\n0.08,0.70\n0.04,0.78\n0.02,0.80');
 await page.locator('#vv-mesh-run').click();
 await page.waitForFunction(()=>document.querySelectorAll('#vv-mesh-result tbody tr').length===3);
 const download=page.waitForEvent('download');await page.locator('#vv-pack').click();
 const pack=await download;assert(pack.suggestedFilename().endsWith('.zip'));
 await pack.saveAs('test-preparation-download.zip');
 await page.setViewportSize({width:390,height:850});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
 await page.locator('#vv-dynamic').screenshot({path:'vv-mobile.png'});
 assert.deepEqual(errors,[]);
 console.log('UI PASS: geometry sync, 1D, 6DOF, time convergence, synthetic comparison, mesh import, ZIP, mobile layout, no runtime errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
